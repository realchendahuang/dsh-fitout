#!/usr/bin/env python3
"""Split the one-piece layout stylesheet into the twelve switchable groups.

The layout layer started life as a single CSS template literal. This script cuts
it at the ``/* ═══ N. title ═══ */`` markers and emits ``sections.js``: a shared
variable block, a small always-on tail, and twelve groups that can be turned off
one at a time.

    python3 scripts/split-sections.py --from <styles.js> --out src/client/sections.js

Rules, so the output stays honest:
  * every byte of the source template literal lands in exactly one group;
  * groups are emitted in source order, so the cascade never changes;
  * sections listed in ALWAYS_ON (the plugin's own settings-row styling) are
    appended after the base block and never switchable.
"""

import argparse
import json
import re

GROUPS = [
    ("tools", "工具行与步骤", "工具调用是走过的痕迹，不是一叠卡片。", [1, 2]),
    ("disclosures", "折叠头", "折起来是一行，展开才知道它做了什么。", [3, 4]),
    ("prose", "正文排版", "答案的呼吸：段落、标题、引用、列表。", [5, 6]),
    ("code", "代码块", "代码要像代码，不像截图。", [7]),
    ("messages", "消息与状态", "你说话的样子，和它等你的样子。", [8, 9]),
    ("composer", "输入框", "打字的地方，应该安静。", [11]),
    ("sidebar", "侧栏", "一屏能看见多少事。", [12]),
    ("chrome", "顶部页签", "上面那一行，越少越好。", [13]),
    ("detail", "展开详情", "展开以后看到的东西，也要体面。", [14, 15]),
    ("actions", "答案操作行", "答案说完，退一步站好。", [16]),
    ("cards", "清单与面板", "它在忙什么，一眼看得见。", [19, 21, 22]),
    ("polish", "全局细节", "滚动与焦点，用起来才知道的地方。", [10, 18]),
]

# Sections that must never be switchable: the plugin's own settings-row styling.
ALWAYS_ON = {17, 20}

MARKER = re.compile(r"^/\* ═+ (\d+)\.\s*(.*?) ?═*\s*\*/?\s*$")


def template_body(source):
    start = source.index("export const CSS = `") + len("export const CSS = `")
    end = source.rindex("`")
    return source[start:end]


def split_sections(body):
    lines = body.split("\n")
    markers = []
    for index, line in enumerate(lines):
        match = MARKER.match(line.strip())
        if match:
            markers.append((index, int(match.group(1))))
    if not markers:
        raise SystemExit("no section markers found")

    chunks = {}
    base = "\n".join(lines[: markers[0][0]]).rstrip("\n")
    for position, (line_number, number) in enumerate(markers):
        stop = markers[position + 1][0] if position + 1 < len(markers) else len(lines)
        chunks[number] = "\n".join(lines[line_number:stop]).rstrip("\n")
    return base, chunks


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--from", dest="source", required=True, help="the one-piece stylesheet (src/client/styles.js)")
    parser.add_argument("--out", dest="out", required=True, help="where to write sections.js")
    args = parser.parse_args()

    with open(args.source, encoding="utf-8") as handle:
        body = template_body(handle.read())
    base, chunks = split_sections(body)

    assigned = {number for _, _, _, numbers in GROUPS for number in numbers}
    always = [number for number in sorted(chunks) if number not in assigned or number in ALWAYS_ON]
    covered = set(assigned) | set(always)
    missing = set(chunks) - covered
    if missing:
        raise SystemExit(f"sections without a group: {sorted(missing)}")

    def literal(text):
        if "`" in text or "${" in text:
            raise SystemExit("a chunk contains a template-literal hazard")
        return text

    groups = sorted(GROUPS, key=lambda group: min(group[3]))
    out = [
        "/** Generated by scripts/split-sections.py — do not edit by hand.",
        " *",
        " * BASE_CSS carries the shared --fto-* variables and the plugin's own",
        " * settings-row styling and is always emitted; every other section is",
        " * emitted only while its group is enabled, in the original cascade order.",
        " */",
        "export const BASE_CSS = `" + literal(base) + "`",
        "",
        "const ALWAYS_TAIL = `" + "\n\n".join(literal(chunks[n]) for n in always) + "`",
        "",
        "export const SECTIONS = Object.freeze([",
    ]
    for group_id, title, desc, numbers in groups:
        css = "\n\n".join(literal(chunks[number]) for number in numbers)
        out += [
            "  {",
            f"    id: {json.dumps(group_id)},",
            f"    title: {json.dumps(title, ensure_ascii=False)},",
            f"    desc: {json.dumps(desc, ensure_ascii=False)},",
            "    css: `" + css + "`,",
            "  },",
        ]
    out += [
        "])",
        "",
        "/** Full stylesheet for a disabled-id set. Unknown ids are harmless. */",
        "export function buildCss(disabled) {",
        "  const off = disabled instanceof Set ? disabled : new Set(disabled ?? [])",
        "  const parts = [BASE_CSS, ALWAYS_TAIL]",
        "  for (const section of SECTIONS) {",
        "    if (!off.has(section.id)) parts.push(section.css)",
        "  }",
        '  return parts.join("\\n")',
        "}",
        "",
    ]

    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print(f"wrote {args.out}: {len(groups)} groups, {sum(len(chunks[n]) for n in chunks)} bytes of CSS")


if __name__ == "__main__":
    main()
