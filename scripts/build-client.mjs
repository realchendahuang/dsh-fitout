/**
 * Build the Client half into the browser artifact the DSH client loader expects:
 * window.__ModuleLoader__.load({ id, factory(require) }).
 *
 * JSX is bundled as CommonJS with react left external (the loader's module table
 * owns the single React instance), then wrapped in the factory so the bundle's
 * `require('react')` calls receive the factory argument.
 */
import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const bundlePath = resolve(root, 'dist', 'client.bundle.cjs')
const outputPath = resolve(root, 'client.js')
const PACKAGE = 'dsh-fitout'

await mkdir(dirname(bundlePath), { recursive: true })

await build({
  absWorkingDir: root,
  entryPoints: [resolve(root, 'src/client/entry.jsx')],
  outfile: bundlePath,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2020'],
  jsx: 'transform',
  external: ['react'],
  logLevel: 'warning',
})

const code = await readFile(bundlePath, 'utf8')
const indented = code
  .split('\n')
  .map((line) => (line.length > 0 ? `    ${line}` : line))
  .join('\n')

const wrapper = `/** Generated by scripts/build-client.mjs — do not edit by hand. */
window.__ModuleLoader__.load({
  id: '${PACKAGE}',
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${indented}
    return module.exports;
  },
});
`

await writeFile(outputPath, wrapper, 'utf8')
console.log('client.js written (%d bytes)', wrapper.length)
